function assertRedactionSafe(obj, label) {
  const serialized = JSON.stringify(obj);
  if (UUID_FULL.test(serialized)) {
    throw new Error(`S05 refresh refused: full UUID detected in ${label}`);
  }
  if (CREDENTIAL_ASSIGNMENT.test(serialized)) {
    throw new Error(`S05 refresh refused: credential assignment detected in ${label}`);
  }
  if (XIAOMI_RE.test(serialized)) {
    throw new Error(`S05 refresh refused: xiaomi or mimo string detected in ${label}`);
  }
}

