  fs.mkdirSync(path.dirname(S05_EVIDENCE), { recursive: true });
  fs.writeFileSync(S05_EVIDENCE, JSON.stringify(s05, null, 2) + '\n');

  // eslint-disable-next-line no-console
  console.log(`[refresh-m015-s05-t10] refreshed ${path.relative(ROOT, S05_EVIDENCE)}`);
  // eslint-disable-next-line no-console
